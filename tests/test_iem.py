from datetime import UTC, date, datetime
from decimal import Decimal

from stratus.collectors.iem import parse_iem_csv, year_chunks


def test_year_chunks_are_resumable_calendar_ranges() -> None:
    assert year_chunks(date(2023, 7, 5), date(2026, 7, 5)) == [
        (date(2023, 7, 5), date(2024, 1, 1)),
        (date(2024, 1, 1), date(2025, 1, 1)),
        (date(2025, 1, 1), date(2026, 1, 1)),
        (date(2026, 1, 1), date(2026, 7, 5)),
    ]


def test_parse_iem_csv_deduplicates_corrections_and_skips_missing_temp() -> None:
    content = """# generated by IEM
station,valid,tmpc,metar
LGA,2026-07-04 00:51,27.78,KLGA 040051Z 27011KT 10SM 28/19 A2992
LGA,2026-07-04 00:51,28.00,KLGA 040051Z COR 27011KT 10SM 28/19 A2992
LGA,2026-07-04 01:51,null,KLGA 040151Z 26010KT 10SM 27/19 A2993
LGA,2026-07-05 00:00,20.00,KLGA 050000Z 26010KT 10SM 20/10 A3000
"""
    values = parse_iem_csv(
        content,
        station_id=1,
        start=date(2026, 7, 4),
        end=date(2026, 7, 5),
    )
    assert len(values) == 1
    assert values[0].obs_time == datetime(2026, 7, 4, 0, 51, tzinfo=UTC)
    assert values[0].temp_c == Decimal("28.00")
    assert "COR" in values[0].raw_metar

